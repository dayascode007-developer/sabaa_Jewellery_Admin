// Generate @font-face CSS for all fonts
export const generateFontFaceCSS = () => {
  return fonts
    .map(
      (font) => `
@font-face {
  font-family: "${font.name}";
  src: url('/fonts/${font.file}') format('truetype');
  font-weight: normal;
  font-style: normal;
}
`
    )
    .join("\n");
};

// Get font options for dropdowns (name + cssFamily + badge)
export const getFontOptions = () => {
  return fonts.map((font) => ({
    name: font.name,
    cssFamily: font.cssFamily,
    badge: font.badge,
  }));
};

// Get font names for validation
export const getFontNames = () => {
  return fonts.map((font) => font.name);
};
